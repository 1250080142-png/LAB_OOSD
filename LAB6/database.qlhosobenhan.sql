CREATE DATABASE QuanLyHoSoBenhAn;
GO

USE QuanLyHoSoBenhAn;
GO

-- 1. Bảng Bệnh Nhân
CREATE TABLE BENH_NHAN (
    maBN VARCHAR(20) PRIMARY KEY,
    hoTen NVARCHAR(100) NOT NULL,
    ngaySinh DATE,
    diaChi NVARCHAR(255),
    dienThoai VARCHAR(15),
    anh3x4 VARCHAR(255)
);

-- 2. Bảng Phiếu Đăng Ký
CREATE TABLE PHIEU_DANG_KY (
    maPDK VARCHAR(20) PRIMARY KEY,
    maBN VARCHAR(20) FOREIGN KEY REFERENCES BENH_NHAN(maBN),
    ngayDangKy DATE,
    lePhiHangNam DECIMAL(10,2)
);

-- 3. Bảng Hồ Sơ Bệnh Án
CREATE TABLE HO_SO_BENH_AN (
    maHS VARCHAR(20) PRIMARY KEY,
    maBN VARCHAR(20) FOREIGN KEY REFERENCES BENH_NHAN(maBN),
    ngayLap DATE
);

-- 4. Bảng Bác Sĩ
CREATE TABLE BAC_SI (
    maBS VARCHAR(20) PRIMARY KEY,
    hoTenBS NVARCHAR(100),
    chuyenKhoa NVARCHAR(100)
);

-- 5. Bảng Phiếu Khám Bệnh
CREATE TABLE PHIEU_KHAM_BENH (
    maPKB VARCHAR(20) PRIMARY KEY,
    maHS VARCHAR(20) FOREIGN KEY REFERENCES HO_SO_BENH_AN(maHS),
    maBS VARCHAR(20) FOREIGN KEY REFERENCES BAC_SI(maBS),
    ngayGioKham DATETIME,
    khoaDieuTri NVARCHAR(100),
    trieuChung NVARCHAR(MAX),
    huyetAp VARCHAR(20),
    thanNhiet FLOAT
);

-- 6. Bảng Xét Nghiệm
CREATE TABLE XET_NGHIEM (
    maXN VARCHAR(20) PRIMARY KEY,
    maPKB VARCHAR(20) FOREIGN KEY REFERENCES PHIEU_KHAM_BENH(maPKB),
    tenXetNghiem NVARCHAR(150),
    ketQuaXN NVARCHAR(MAX)
);

-- 7. Bảng Toa Thuốc
CREATE TABLE TOA_THUOC (
    maTT VARCHAR(20) PRIMARY KEY,
    maPKB VARCHAR(20) FOREIGN KEY REFERENCES PHIEU_KHAM_BENH(maPKB),
    danhSachThuoc NVARCHAR(MAX),
    cachDung NVARCHAR(MAX)
);

-- 8. Bảng Lịch Hẹn
CREATE TABLE LICH_HEN (
    maLH VARCHAR(20) PRIMARY KEY,
    maBN VARCHAR(20) FOREIGN KEY REFERENCES BENH_NHAN(maBN),
    maHS VARCHAR(20) FOREIGN KEY REFERENCES HO_SO_BENH_AN(maHS),
    ngayGioHen DATETIME,
    loaiHen NVARCHAR(50)
);